'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.join(__dirname, '..', 'renderer');
test('视频指示条外链样式，开始、暂停、继续和保存状态可见', async () => {
  const html = fs.readFileSync(path.join(root, 'video-indicator.html'), 'utf8');
  assert.match(html, /style-src 'self'/);
  assert.doesNotMatch(html, /<style\b|\sstyle=/i);
  assert.match(html, /href="video-indicator\.css"/);
  assert.match(html, /type="checkbox" id="audio-system"/);
  assert.match(html, /type="checkbox" id="audio-mic"/);
  assert.doesNotMatch(html, /\bchecked\b/);
  assert.ok(fs.readFileSync(path.join(root, 'video-indicator.css'), 'utf8').includes('#start'));
  const nodes = Object.fromEntries(['state','clock','start','pause','stop','cancel','audio-options','audio-system','audio-mic'].map(id => [id, { hidden: false, checked: false, textContent: '', addEventListener(type, fn) { this[type] = fn; } }]));
  const actions = []; let notify;
  const context = { document: { querySelector: s => nodes[s.slice(1)] }, video: { action: async (action, choices) => { actions.push({ action, choices }); return true; }, onIndicator: fn => { notify = fn; } }, setInterval: () => 1, clearInterval() {} };
  vm.runInNewContext(fs.readFileSync(path.join(root, 'video-indicator.js'), 'utf8'), context);
  assert.equal(nodes.start.hidden, false); assert.equal(nodes.stop.hidden, true);
  assert.equal(nodes['audio-system'].checked, false); assert.equal(nodes['audio-mic'].checked, false);
  nodes['audio-mic'].checked = true;
  await nodes.start.click(); assert.equal(actions[0].action, 'start');
  assert.equal(actions[0].choices.systemAudio, false); assert.equal(actions[0].choices.microphone, true);
  assert.equal(nodes['audio-options'].hidden, true); assert.equal(nodes['audio-mic'].disabled, true);
  await nodes.start.click(); assert.equal(actions.length, 1, '不可重入');
  notify({ state: 'recording' }); assert.equal(nodes.pause.hidden, false); assert.equal(nodes.stop.hidden, false);
  await nodes.pause.click(); assert.equal(actions[1].action, 'pause');
  notify({ state: 'paused' }); assert.equal(nodes.pause.textContent, '继续');
  await nodes.pause.click(); assert.equal(actions[2].action, 'resume');
  notify({ state: 'unsaved' }); assert.equal(nodes.start.textContent, '重试保存');
});
